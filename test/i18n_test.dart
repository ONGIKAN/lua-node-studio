import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:lua_node_studio/codegen/lua_generator.dart';
import 'package:lua_node_studio/l10n/l10n.dart';
import 'package:lua_node_studio/l10n/language_store.dart';
import 'package:lua_node_studio/main.dart';
import 'package:lua_node_studio/ui/editor_page.dart';
import 'package:lua_node_studio/models/node_spec.dart';
import 'package:lua_node_studio/samples/sample_catalog.dart';
import 'package:lua_node_studio/samples/sample_graph.dart';

void main() {
  setUp(() => L10n.setLanguage(AppLanguage.zh));
  tearDown(() => L10n.setLanguage(AppLanguage.zh));

  test('节点注册表随语言切换返回中英文文案', () {
    expect(NodeRegistry.of('func').title, '定义函数');
    expect(NodeRegistry.of('call').title, '调用函数');
    expect(categoryLabel(NodeCategory.control), '控制');
    expect(PortType.number.label, '数字');

    L10n.setLanguage(AppLanguage.en);

    expect(NodeRegistry.of('func').title, 'Define function');
    expect(NodeRegistry.of('call').title, 'Call function');
    expect(NodeRegistry.of('print').title, 'Print');
    expect(categoryLabel(NodeCategory.control), 'Control');
    expect(categoryLabel(NodeCategory.function), 'Function');
    expect(PortType.number.label, 'Number');
    expect(L10n.t('中文', 'English'), 'English');
    expect(L10n.isEnglish, isTrue);
  });

  test('函数节点的参数端口在英文下仍是同一批参数名', () {
    L10n.setLanguage(AppLanguage.en);
    final n = buildSampleGraph().nodes.firstWhere((e) => e.type == 'start');
    expect(n.spec.title, 'Start');
    final gen = LuaGenerator(buildSampleGraph()).generate();
    // 代码注释跟随语言，Lua 源码本身与语言无关
    expect(gen.code, contains('-- Generated by Lua Node Studio'));
    expect(gen.code, contains('-- Graph: Sample: sum 1 to 10'));
    expect(gen.code, contains('print("sum =", sum)'));
    expect(gen.warnings, isEmpty);
  });

  test('示例清单随语言切换展示英文标题', () {
    expect(kSamples.first.displayTitle, '1 到 10 求和');
    expect(kSamples[1].displayTitle, '阶乘 factorial');

    L10n.setLanguage(AppLanguage.en);
    expect(kSamples.first.displayTitle, 'Sum 1 to 10');
    expect(kSamples[1].displayTitle, 'Factorial');
    expect(kSamples[4].displayDescription, contains('97'));
  });

  test('引擎版本说明跟随语言', () {
    expect(L10n.isEnglish, isFalse);
    expect(L10n.t('Lua 5.3 (纯 Dart)', 'Lua 5.3 (pure Dart)'),
        'Lua 5.3 (纯 Dart)');
    L10n.setLanguage(AppLanguage.en);
    expect(L10n.t('Lua 5.3 (纯 Dart)', 'Lua 5.3 (pure Dart)'),
        'Lua 5.3 (pure Dart)');
  });

  testWidgets('顶栏菜单可以切换中英文界面', (tester) async {
    tester.view.physicalSize = const Size(2400, 3000);
    tester.view.devicePixelRatio = 2.0;
    addTearDown(tester.view.reset);

    await tester.pumpWidget(const LuaNodeApp(home: EditorPage()));
    await tester.pumpAndSettle();

    // 默认中文：菜单里提供切换到 English 的入口
    await tester.tap(find.byIcon(Icons.more_vert).first);
    await tester.pumpAndSettle();
    expect(find.text('English'), findsOneWidget);

    await tester.tap(find.text('English'));
    await tester.pumpAndSettle();

    // 切到英文后画布工具栏、节点标题都变成英文
    expect(L10n.isEnglish, isTrue);
    expect(find.text('Nodes'), findsOneWidget);
    expect(find.text('Lua code'), findsOneWidget);

    // 再打开菜单，入口变成切回中文
    await tester.tap(find.byIcon(Icons.more_vert).first);
    await tester.pumpAndSettle();
    expect(find.text('中文'), findsOneWidget);
    await tester.tap(find.text('中文'));
    await tester.pumpAndSettle();
    expect(L10n.isEnglish, isFalse);
    expect(find.text('节点'), findsOneWidget);
  });

  testWidgets('切换语言后默认示例图仍然可以运行并输出 55', (tester) async {
    tester.view.physicalSize = const Size(2400, 3000);
    tester.view.devicePixelRatio = 2.0;
    addTearDown(tester.view.reset);

    L10n.setLanguage(AppLanguage.en);
    await tester.pumpWidget(const LuaNodeApp(home: EditorPage()));
    await tester.pumpAndSettle();

    // 英文界面下节点标题已切换
    expect(find.text('Nodes'), findsOneWidget);
    await tester.tap(find.byIcon(Icons.play_arrow_rounded));
    await tester.pump();

    // 真实运行时在隔离区里跑，需要 runAsync 让出真实事件循环
    for (var i = 0; i < 8; i++) {
      await tester.runAsync(() async {
        await Future<void>.delayed(const Duration(milliseconds: 200));
      });
      await tester.pump(const Duration(milliseconds: 120));
      if (find.textContaining('55').evaluate().isNotEmpty) break;
    }
    expect(find.textContaining('55'), findsWidgets);
  });

  test('语言持久化失败时静默降级', () async {
    // 测试环境没有 path_provider 插件，apply 不应抛异常
    await LanguageStore.apply(AppLanguage.en);
    expect(L10n.isEnglish, isTrue);
    await LanguageStore.apply(AppLanguage.zh);
    expect(L10n.isEnglish, isFalse);
  });
}

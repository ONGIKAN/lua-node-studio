import '../l10n/l10n.dart';
import '../models/graph.dart';
import '../models/node_spec.dart';

class LuaGenResult {
  final String code;
  final List<String> warnings;
  const LuaGenResult(this.code, this.warnings);
}

/// 把节点图编译成 Lua 源码。
///
/// 执行流（exec 端口）决定语句顺序；数据流（data 端口）递归展开成表达式。
/// 分支/循环的收口采用"汇合点"规则：两条分支链路上第一个共同节点即为 continue 点，
/// 因此不需要额外的 merge 节点。
class LuaGenerator {
  final NodeGraph graph;
  final StringBuffer _out = StringBuffer();
  final Set<String> _declared = {};
  final List<String> _warnings = [];
  int _indent = 0;
  int _budget = 4000;

  /// 调用节点的返回值变量名，以及该变量是否已经生成声明。
  final Map<String, String> _retVars = {};
  final Set<String> _retDeclared = {};
  int _retSeed = 0;

  LuaGenerator(this.graph);

  LuaGenResult generate() {
    final start = graph.startNode;
    if (start == null) {
      return LuaGenResult(
        L10n.t('-- 缺少「开始」节点，无法生成代码',
            '-- Missing the "Start" node; cannot generate code'),
        const [],
      );
    }
    _out.writeln(L10n.t('-- 由 Lua Node Studio 自动生成',
        '-- Generated by Lua Node Studio'));
    _out.writeln(L10n.t('-- 图名：${graph.name}', '-- Graph: ${graph.name}'));
    _out.writeln();
    _emitChain(start.id, <String>{});
    final code = _out.toString().trimRight();
    return LuaGenResult(code, List.unmodifiable(_warnings));
  }

  void _line(String s) {
    if (s.isEmpty) {
      _out.writeln();
      return;
    }
    _out.writeln('${'  ' * _indent}$s');
  }

  void _emitChain(String? nodeId, Set<String> guard, {String? stopAt}) {
    var cur = nodeId;
    while (cur != null && cur != stopAt) {
      if (_budget-- <= 0) {
        _warnings.add(L10n.t('语句数量超出上限，已截断',
            'Too many statements; output truncated'));
        break;
      }
      if (guard.contains(cur)) {
        _warnings.add(L10n.t('检测到环路，已在节点 $cur 处停止',
            'Loop detected; stopped at node $cur'));
        break;
      }
      guard.add(cur);
      final node = graph.byId(cur);
      if (node == null) break;
      cur = _emitNode(node, guard, stopAt);
    }
  }

  String? _emitNode(GraphNode node, Set<String> guard, String? stopAt) {
    switch (node.type) {
      case 'start':
        return graph.nextExec(node.id, 'out');
      case 'print':
        _line('print(${_expr(node, 'value')})');
        return graph.nextExec(node.id, 'out');
      case 'assign':
        final name = _ident(node.field('name'), 'x');
        final value = _expr(node, 'value');
        if (_declared.add(name)) {
          _line('local $name = $value');
        } else {
          _line('$name = $value');
        }
        return graph.nextExec(node.id, 'out');
      case 'call':
        return _emitCall(node);
      case 'stop':
        final hasValue = graph.linkInto(node.id, 'value') != null ||
            node.literal('value').trim().isNotEmpty;
        _line(hasValue ? 'return ${_expr(node, 'value')}' : 'return');
        return null;
      case 'comment':
        for (final l in node.field('text').split('\n')) {
          _line('-- $l');
        }
        return null;
      case 'if':
        return _emitIf(node, guard);
      case 'for':
        return _emitFor(node, guard);
      case 'while':
        return _emitWhile(node, guard);
      case 'func':
        return _emitFunc(node, guard);
      default:
        _warnings.add(L10n.t(
            '「${node.spec.title}」不是语句节点，不能串在执行流上',
            '"${node.spec.title}" is not a statement node and cannot be used in the exec flow'));
        return null;
    }
  }

  /// 调用节点最多支持 3 个参数端口；空着的尾部参数会被省略，
  /// 中间的空洞补 `nil` 以保持参数位置。
  String? _emitCall(GraphNode node) {
    final name = _ident(node.field('name'), 'myFunc');
    var lastUsed = 0;
    for (var i = 1; i <= 3; i++) {
      final portId = 'arg$i';
      final linked = graph.linkInto(node.id, portId) != null;
      if (linked || node.literal(portId).trim().isNotEmpty) lastUsed = i;
    }
    final args = <String>[];
    for (var i = 1; i <= lastUsed; i++) {
      final portId = 'arg$i';
      if (graph.linkInto(node.id, portId) != null) {
        args.add(_expr(node, portId));
      } else {
        final lit = node.literal(portId).trim();
        args.add(lit.isEmpty ? 'nil' : lit);
      }
    }
    final call = '$name(${args.join(', ')})';
    final usesRet =
        graph.linksFromNode(node.id).any((l) => l.fromPort == 'ret');
    if (usesRet) {
      final v = _retVar(node.id);
      _retDeclared.add(node.id);
      _line('local $v = $call');
    } else {
      _line(call);
    }
    return graph.nextExec(node.id, 'out');
  }

  String? _emitIf(GraphNode node, Set<String> guard) {
    final cond = _expr(node, 'cond');
    final thenStart = graph.nextExec(node.id, 'then');
    final elseStart = graph.nextExec(node.id, 'else');
    final converge = _findConvergence(thenStart, elseStart);

    _line('if $cond then');
    _indent++;
    if (thenStart == null) {
      _line(L10n.t('-- 空分支', '-- empty branch'));
    } else {
      _emitChain(thenStart, <String>{...guard}, stopAt: converge);
    }
    _indent--;
    if (elseStart != null && elseStart != converge) {
      _line('else');
      _indent++;
      _emitChain(elseStart, <String>{...guard}, stopAt: converge);
      _indent--;
    }
    _line('end');
    return converge;
  }

  String? _emitFor(GraphNode node, Set<String> guard) {
    final from = _expr(node, 'from');
    final to = _expr(node, 'to');
    final step = _expr(node, 'step');
    final varName = _ident(node.field('var'), 'i');
    final bodyStart = graph.nextExec(node.id, 'body');
    final doneStart = graph.nextExec(node.id, 'done');
    final converge = _convergeForLoop(node, bodyStart, doneStart);

    final head = (step == '1' || step.isEmpty)
        ? 'for $varName = $from, $to do'
        : 'for $varName = $from, $to, $step do';
    _line(head);
    _indent++;
    if (bodyStart == null) {
      _line(L10n.t('-- 空循环体', '-- empty loop body'));
    } else {
      _emitChain(bodyStart, <String>{...guard, node.id},
          stopAt: converge ?? node.id);
    }
    _indent--;
    _line('end');
    if (converge != null) return converge;
    if (doneStart != null) {
      _emitChain(doneStart, <String>{...guard, node.id});
    }
    return null;
  }

  String? _emitWhile(GraphNode node, Set<String> guard) {
    final cond = _expr(node, 'cond');
    final bodyStart = graph.nextExec(node.id, 'body');
    final doneStart = graph.nextExec(node.id, 'done');
    final converge = _convergeForLoop(node, bodyStart, doneStart);

    _line('while $cond do');
    _indent++;
    if (bodyStart == null) {
      _line(L10n.t('-- 空循环体', '-- empty loop body'));
    } else {
      _emitChain(bodyStart, <String>{...guard, node.id},
          stopAt: converge ?? node.id);
    }
    _indent--;
    _line('end');
    if (converge != null) return converge;
    if (doneStart != null) {
      _emitChain(doneStart, <String>{...guard, node.id});
    }
    return null;
  }

  String? _emitFunc(GraphNode node, Set<String> guard) {
    final name = _ident(node.field('name'), 'myFunc');
    final rawParams = node.field('params').trim();
    final params = parseParamNames(rawParams);
    if (rawParams.isNotEmpty && params.isEmpty) {
      _warnings.add(L10n.t(
          '函数参数「$rawParams」不是合法的参数列表，已忽略',
          'Invalid function parameter list "$rawParams"; ignored'));
    }
    final bodyStart = graph.nextExec(node.id, 'body');
    final doneStart = graph.nextExec(node.id, 'done');
    final converge = _convergeForLoop(node, bodyStart, doneStart);

    _declared.add(name);
    _declared.addAll(params);
    _line('local function $name(${params.join(', ')})');
    _indent++;
    if (bodyStart == null) {
      _line(L10n.t('-- 空函数体', '-- empty function body'));
    } else {
      _emitChain(bodyStart, <String>{...guard, node.id},
          stopAt: converge ?? node.id);
    }
    _indent--;
    _line('end');
    if (converge != null) return converge;
    if (doneStart != null) {
      _emitChain(doneStart, <String>{...guard, node.id});
    }
    return null;
  }

  /// 循环体/函数体如果"绕回自己"，说明用的是回环写法，此时不做汇合点分析，
  /// 结束端口之后的链路就是后续流程。
  String? _convergeForLoop(
      GraphNode node, String? bodyStart, String? doneStart) {
    if (bodyStart == null || doneStart == null) return null;
    if (_linearChain(bodyStart).contains(node.id)) return null;
    return _findConvergence(bodyStart, doneStart);
  }

  // ---------------------------------------------------------------- 数据流

  String _retVar(String nodeId) =>
      _retVars.putIfAbsent(nodeId, () => '__ret_${_retSeed++}');

  int? _paramIndex(String portId) {
    if (!portId.startsWith('p')) return null;
    return int.tryParse(portId.substring(1));
  }

  String _expr(GraphNode node, String portId, [int depth = 0]) {
    if (depth > 40) return 'nil';
    final link = graph.linkInto(node.id, portId);
    if (link == null) return node.literal(portId);
    final src = graph.byId(link.fromNode);
    if (src == null) return 'nil';
    return _exprOfOutput(src, link.fromPort, depth + 1);
  }

  String _exprOfOutput(GraphNode src, String portId, int depth) {
    if (depth > 40) {
      _warnings.add(L10n.t(
          '数据链路过深或存在环，已在「${src.spec.title}」截断',
          'Data flow too deep or cyclic; truncated at "${src.spec.title}"'));
      return 'nil';
    }
    switch (src.type) {
      case 'number':
        return _number(src.field('value'));
      case 'text':
        return _luaString(src.field('value'));
      case 'bool':
        return src.field('value') == 'false' ? 'false' : 'true';
      case 'var':
        return _ident(src.field('name'), 'x');
      case 'math':
        final op = src.field('op');
        return '(${_expr(src, 'a', depth)} $op ${_expr(src, 'b', depth)})';
      case 'compare':
        final op = src.field('op');
        return '(${_expr(src, 'a', depth)} $op ${_expr(src, 'b', depth)})';
      case 'logic':
        final op = src.field('op');
        if (op == 'not') return '(not ${_expr(src, 'a', depth)})';
        return '(${_expr(src, 'a', depth)} $op ${_expr(src, 'b', depth)})';
      case 'func':
        // 函数参数端口：p0/p1/... 直接就是函数体里的局部变量名
        final idx = _paramIndex(portId);
        final params = parseParamNames(src.field('params'));
        if (idx == null || idx >= params.length) return 'nil';
        return params[idx];
      case 'call':
        if (portId == 'ret') {
          if (!_retDeclared.contains(src.id)) {
            _warnings.add(L10n.t(
                '「${src.spec.title}」的返回值在调用语句之前被使用',
                'The return value of "${src.spec.title}" is used before the call statement'));
          }
          return _retVar(src.id);
        }
        _warnings.add(L10n.t('「${src.spec.title}」没有可用的数据输出',
            '"${src.spec.title}" has no usable data output'));
        return 'nil';
      default:
        _warnings.add(L10n.t('「${src.spec.title}」没有可用的数据输出',
            '"${src.spec.title}" has no usable data output'));
        return 'nil';
    }
  }

  String _number(String raw) {
    final v = raw.trim();
    if (v.isEmpty) return '0';
    if (double.tryParse(v) == null) {
      _warnings.add(L10n.t('数字节点内容「$v」不是合法数字，已按 0 处理',
          'Number node value "$v" is not a valid number; using 0'));
      return '0';
    }
    return v;
  }

  String _luaString(String raw) {
    final escaped = raw
        .replaceAll('\\', r'\\')
        .replaceAll('"', r'\"')
        .replaceAll('\n', r'\n')
        .replaceAll('\r', r'\r')
        .replaceAll('\t', r'\t');
    return '"$escaped"';
  }

  String _ident(String raw, String fallback) {
    final v = raw.trim();
    if (v.isNotEmpty &&
        RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(v) &&
        !luaKeywords.contains(v)) {
      return v;
    }
    _warnings.add(L10n.t('「$raw」不是合法 Lua 标识符，已替换为 $fallback',
        '"$raw" is not a valid Lua identifier; replaced with $fallback'));
    return fallback;
  }

  // -------------------------------------------------------------- 汇合检测

  String? _findConvergence(String? a, String? b) {
    if (a == null || b == null) return null;
    final chainA = _linearChain(a);
    final chainB = _linearChain(b).toSet();
    for (final id in chainA) {
      if (chainB.contains(id)) return id;
    }
    return null;
  }

  List<String> _linearChain(String? start) {
    final ids = <String>[];
    final seen = <String>{};
    var cur = start;
    while (cur != null && ids.length < 300) {
      if (!seen.add(cur)) break;
      ids.add(cur);
      final node = graph.byId(cur);
      if (node == null) break;
      cur = _firstExecOut(node);
    }
    return ids;
  }

  String? _firstExecOut(GraphNode node) {
    for (final p in const ['out', 'then', 'done', 'body', 'else']) {
      if (node.spec.outputById(p) != null) {
        final nx = graph.nextExec(node.id, p);
        if (nx != null) return nx;
      }
    }
    for (final p in node.spec.outputs) {
      if (p.type == PortType.exec) {
        final nx = graph.nextExec(node.id, p.id);
        if (nx != null) return nx;
      }
    }
    return null;
  }
}
